"""Markdown tables from the final-analysis products (no Parquet access).

Usage: .venv/bin/python scripts/final_tables.py [--dir reports/final-analysis]
Reads <dir>/core/pilot_table.csv (scripts/analyze_pilots.py) and the outputs of
scripts/final_analysis.py; writes <dir>/final_tables.md.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def g(x: float) -> str:
    x = float(x)
    if x == 0:
        return "0"
    if abs(x) >= 1e6:
        return f"{x / 1e6:.3g}M"
    if abs(x) >= 1e4:
        return f"{x / 1e3:.0f}k"
    if abs(x) >= 100:
        return f"{x:.0f}"
    return f"{x:.3g}"


def table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="reports/final-analysis")
    d = Path(ap.parse_args().dir)
    core = list(csv.DictReader((d / "core" / "pilot_table.csv").open()))
    allin = {(r["format"], r["pairing_id"]): r for r in csv.DictReader((d / "allin.csv").open())}
    name = lambda r: f"{r['format']} {r['pairing_id'].split('-', 1)[0]}"  # noqa: E731
    md = ["# Final core tables", "",
          "Generated by scripts/final_tables.py from reports/final-analysis. Unit: matched block. "
          "Power: two-sided alpha 0.05, normal approximation. Nit D includes penalty transfers.", ""]

    md += ["## A. Corpus and distribution", ""]
    md.append(table(
        ["pairing", "blocks", "hands/blk", "played hands", "mean BB/100 [95% CI]", "sigma_D [boot 95%]", "D=0", "skew",
         "ex.kurt", "q0.0001", "q0.001", "q0.999", "q0.9999"],
        [[name(r), g(r["n_blocks"]), f"{float(r['hands_per_block']):.1f}", g(float(r["n_blocks"]) * float(r["hands_per_block"])),
          f"{float(r['mean_bb100']):+.2f} [{float(r['ci_bb100_lo']):+.2f}, {float(r['ci_bb100_hi']):+.2f}]",
          f"{float(r['sd_D']):.2f} [{float(r['sd_boot_lo']):.2f}, {float(r['sd_boot_hi']):.2f}]",
          f"{float(r['frac_zero']):.3f}", f"{float(r['skew']):.2f}", f"{float(r['excess_kurtosis']):.1f}",
          g(r["q0.0001"]), g(r["q0.001"]), g(r["q0.999"]), g(r["q0.9999"])] for r in core]))

    md += ["", "## B. Variance concentration and mechanism", "",
           "Share of total squared deviation carried by the top-f fraction of blocks.", ""]
    fr = ["0.1", "0.05", "0.01", "0.005", "0.001", "0.0005", "0.0001"]
    md.append(table(
        ["pairing"] + [f"top {float(f) * 100:g}%" for f in fr] +
        ["all-in/hand", "showdown/hand", "mean pot BB", "max pot BB", "blocks w/ all-in", "sq-dev share of those",
         "all-in & D≠0 blocks", "share"],
        [[name(r)] + [f"{float(r['conc_top' + f]):.3f}" if r["conc_top" + f] not in ("", "None") else "–" for f in fr] +
         [f"{float(r['allin_rate']):.4f}", f"{float(r['showdown_rate']):.3f}", f"{float(r['mean_pot_bb']):.1f}",
          f"{float(r['max_pot_bb']):.0f}", f"{float(r['frac_blocks_with_allin']):.3f}",
          f"{float(r['var_share_blocks_with_allin']):.3f}",
          f"{float(allin[(r['format'], r['pairing_id'])]['frac_blocks_allin_decisive']):.3f}",
          f"{float(allin[(r['format'], r['pairing_id'])]['share_allin_decisive']):.3f}"] for r in core]))

    md += ["", "## C. Requirements (80% power; 95% in brackets) and cost", ""]
    dl = ["0.25", "0.5", "1", "2", "5"]
    md.append(table(
        ["pairing"] + [f"blocks @{x}" for x in dl] + [f"hands @{x}" for x in dl],
        [[name(r)] + [f"{g(r[f'blocks_{x}bb100_p80'])} [{g(r[f'blocks_{x}bb100_p95'])}]" for x in dl] +
         [f"{g(r[f'hands_{x}bb100_p80'])} [{g(r[f'hands_{x}bb100_p95'])}]" for x in dl] for r in core]))
    md += [""]
    md.append(table(
        ["pairing", "blocks/s per worker", "blocks/s measured (8w)", "wall h @1 BB/100 (8w)", "CPU h @1 BB/100",
         "bytes/block", "storage @1 BB/100", "BB/100 at d=0.01", "hands at d=0.01"],
        [[name(r), f"{float(r['core_blocks_per_s']):.1f}", f"{float(r['agg_blocks_per_s_8w']):.0f}",
          f"{float(r['wall_h_8w_1bb100_p80']):.3g}", f"{float(r['cpu_h_1bb100_p80']):.3g}",
          f"{float(r['bytes_per_block']):.0f}", f"{float(r['bytes_per_block']) * float(r['blocks_1bb100_p80']) / 1e6:.0f} MB",
          f"{float(r['bb100_at_d0.01']):.2f}", g(r["hands_d0.01"])] for r in core]))

    rk = json.loads((d / "ranking.json").read_text())
    md += ["", "## D. Median p1-p3 burden at 1 BB/100, 80% power", ""]
    for metric, lab in (("blocks", "blocks"), ("hands", "played hands"), ("wall_h", "wall-clock h (8 workers, measured)")):
        m = rk["metric"][metric]
        md += [f"### {lab}  (largest/smallest median {m['largest_over_smallest_median']:.1f}x)", ""]
        rows = []
        for f in m["order"]:
            x = m["formats"][f]
            rows.append([f, g(x["median"]), f"[{g(x['median_ci'][0])}, {g(x['median_ci'][1])}]",
                         f"{g(x['min'])} – {g(x['max'])}", f"{x['pairing_spread']:.2f}x"])
        md.append(table(["format", "median", "sampling 95% CI", "p1–p3 range", "max/min"], rows))
        o = m["order"]
        md += ["", table(["neighbours", "ratio of medians", "P_boot", "pairing ranges overlap", "same-role agreement"],
                         [[f"{a} < {b}", f"{m['pairs'][f'{a} < {b}']['ratio_of_medians']:.2f}",
                           f"{m['pairs'][f'{a} < {b}']['p_boot']:.3f}",
                           str(m["pairs"][f"{a} < {b}"]["pairing_ranges_overlap"]),
                           f"{m['pairs'][f'{a} < {b}']['roles_agreeing']}/3"] for a, b in zip(o, o[1:])]), ""]

    conv = list(csv.DictReader((d / "convergence.csv").open()))
    md += ["## E. Pilot (prefix) vs final, and spread of disjoint pilot-size windows", ""]
    md.append(table(
        ["pairing", "pilot n", "sigma pilot→final", "kurt pilot→final", "top1% pilot→final", "top0.1% pilot→final",
         "hands@1 pilot/final", "windows", "window hands ratio min/med/max", "delta-method rel SE", "window rel SD"],
        [[f"{r['format']} {r['pairing_id'][:2]}", g(r["pilot_n"]), f"{float(r['sd_prefix']):.2f}→{float(r['sd_full']):.2f}",
          f"{float(r['kurt_prefix']):.0f}→{float(r['kurt_full']):.0f}", f"{float(r['top1_prefix']):.2f}→{float(r['top1_full']):.2f}",
          f"{float(r['top01_prefix']):.2f}→{float(r['top01_full']):.2f}", f"{float(r['hands_ratio_prefix']):.2f}",
          r["windows"], f"{float(r['window_hands_ratio_min']):.2f}/{float(r['window_hands_ratio_median']):.2f}/{float(r['window_hands_ratio_max']):.2f}",
          f"{float(r['delta_method_rel_se']):.3f}", f"{float(r['window_sd_rel_sd']):.3f}"] for r in conv]))
    (d / "final_tables.md").write_text("\n".join(md) + "\n")
    print(f"wrote {d}/final_tables.md")


if __name__ == "__main__":
    main()
